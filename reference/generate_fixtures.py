"""Export reference results for the JavaScript test suite.

Run from the catapult-tool folder:

    python reference/generate_fixtures.py

It writes web/tests/fixtures.js, a plain script (not JSON) so the test page
also works when opened straight from disk (file://), where fetch() is blocked.
"""

from __future__ import annotations

import itertools
import json
import math
import sys
from dataclasses import asdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "scoreboard"))

from catapult_model import (  # noqa: E402
    CatapultParams,
    effective_mass,
    launch_speed,
    launch_state,
    max_pull_back,
    released_energy,
    simulate,
)
from scoring import score_shot  # noqa: E402

OUT = ROOT / "web" / "tests" / "fixtures.js"

# Python field name -> JS field name.
JS_NAMES = {
    "l_left": "lLeft",
    "l_right": "lRight",
    "l_foot": "lFoot",
    "pivot_height": "pivotHeight",
    "theta_i": "thetaI",
    "theta_f": "thetaF",
    "k": "k",
    "l0": "l0",
    "inertia": "inertia",
    "mass": "mass",
    "efficiency": "efficiency",
    "drag_model": "dragModel",
    "drag": "drag",
    "release_offset": "releaseOffset",
    "g": "g",
}


def to_js(p: CatapultParams) -> dict:
    return {JS_NAMES[k]: v for k, v in asdict(p).items()}


def cases() -> list[tuple[str, CatapultParams]]:
    base = CatapultParams()
    out = [
        ("defaults", base),
        (
            "original notebook values (bug fixed)",
            base.with_(theta_i=3 * math.pi / 4, theta_f=math.pi / 6, inertia=1e-3, pivot_height=0.03),
        ),
        ("spring rest length", base.with_(l0=0.02)),
        ("slack spring", base.with_(l0=0.5)),
        ("release offset", base.with_(release_offset=math.radians(-6))),
        ("half efficiency", base.with_(efficiency=0.5)),
    ]
    drags = [("none", 0.0), ("linear", 2e-3), ("quadratic", 1e-4), ("quadratic", 1e-3)]
    for (model, coeff), th_i, th_f, k in itertools.product(drags, (70, 110, 150), (15, 30, 45, 60), (60, 160)):
        p = base.with_(
            theta_i=math.radians(th_i),
            theta_f=math.radians(th_f),
            k=k,
            l0=0.02,
            efficiency=0.6,
            drag_model=model,
            drag=coeff,
        )
        out.append((f"{model} drag={coeff} th_i={th_i} th_f={th_f} k={k}", p))
    return out


def main() -> None:
    model_cases = []
    for name, p in cases():
        t_land, x_land, _ = simulate(p)
        model_cases.append(
            {
                "name": name,
                "params": to_js(p),
                "expected": {
                    "releasedEnergy": released_energy(p),
                    "effectiveMass": effective_mass(p),
                    "launchSpeed": launch_speed(p),
                    "launchState": launch_state(p).tolist(),
                    "maxPullBack": max_pull_back(p),
                    "range": x_land,
                    "time": t_land,
                },
            }
        )

    misses = [0, 0.01, -0.0499, 0.05, -0.05, 0.0999, 0.1, 0.15, 0.2449, 0.45, 0.4999, 0.5, 0.55, 1.0, -2.0]
    score_cases = [{"miss": m, "points": score_shot(m)} for m in misses]

    doc = {"generator": "reference/generate_fixtures.py", "model": model_cases, "scoring": score_cases}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by reference/generate_fixtures.py -- do not edit by hand.\n"
        "window.REFERENCE_FIXTURES = " + json.dumps(doc, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(model_cases)} model cases and {len(score_cases)} scoring cases to {OUT}")


if __name__ == "__main__":
    main()
